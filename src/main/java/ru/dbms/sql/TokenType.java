package ru.dbms.sql;

/** Вид кусочка запроса, на которые лексер режет текст. */
public enum TokenType {

    /** Слово: имя таблицы, имя колонки или ключевое слово языка. */
    IDENTIFIER,

    /** Число: целое или с дробной частью. */
    NUMBER,

    /** Текст в одинарных кавычках. */
    STRING,

    /** Знак: запятая, скобка, звёздочка, точка с запятой или знак сравнения. */
    SYMBOL,

    /** Признак конца запроса. */
    EOF
}